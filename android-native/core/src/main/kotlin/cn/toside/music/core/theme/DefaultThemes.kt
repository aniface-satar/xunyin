    /** 按内置主题定义生成完整主题（对应 themes.ts 的数组项）。 */
    fun generate(): List<Theme> =
        all.map { t ->
            Theme(
                id = t.id,
                name = t.name,
                isDark = t.isDark,
                isCustom = false,
                themeColors = ThemeColors.createThemeColors(t.primary, t.font, t.isDark),
                extInfo = t.extInfo,
            )
        }

    private fun defaultTheme(
        id: String,
        name: String,
        isDark: Boolean,
        primary: String,
        font: String,
        appBackground: String,
        mainBackground: String,
        badgePrimary: String,
        badgeSecondary: String,
        badgeTertiary: String,
        bgImage: String = "",
    ): DefaultTheme =
        DefaultTheme(
            id = id,
            name = name,
            isDark = isDark,
            primary = primary,
            font = font,
            extInfo =
                ThemeExtInfo(
                    appBackground = appBackground,
                    mainBackground = mainBackground,
                    bgImage = bgImage,
                    bgImagePosition = "center",
                    bgImageSize = "cover",
                    badgePrimary = badgePrimary,
                    badgeSecondary = badgeSecondary,
                    badgeTertiary = badgeTertiary,
                ),
        )
