// 默认主题表 —— 从 RN 侧 src/theme/themes/createThemes.js 的 defaultThemes
// 数组逐项移植（17 个内置主题）。
//
// config 中的 extInfo（c-app-background 等）保持原键原值；
// themeColors 由 [ThemeColors.createThemeColors] 按 primary/font/isDark 生成，
// 与 RN 侧生成物 themes.ts 的键值一一对应（黄金单测锁死）。

/** 单个内置主题的原始配置（primary/font 之外的部分）。 */
data class ThemeExtInfo(
    val appBackground: String,
    val mainBackground: String,
    val bgImage: String,
    val bgImagePosition: String,
    val bgImageSize: String,
    val badgePrimary: String,
    val badgeSecondary: String,
    val badgeTertiary: String,
)

/** 内置主题定义。 */
data class DefaultTheme(
    val id: String,
    val name: String,
    val isDark: Boolean,
    val primary: String,
    val font: String?,
    val extInfo: ThemeExtInfo,
)

/** 生成的完整主题（对应 themes.ts 的一项）。 */
data class Theme(
    val id: String,
    val name: String,
    val isDark: Boolean,
    val isCustom: Boolean,
    val themeColors: Map<String, String>,
    val extInfo: ThemeExtInfo,
)

