/**
 * 背景层淡入的两段时长。
 *
 * 为什么拆两段：只有纯色底那一段在动亮度（主题底 L*~100 → 场 L*~33），而白字必须跟底色同帧翻
 * （墨色只能翻不能淡），于是"底色淡多久"直接等于"白字糊多久"。Easing.out(quad) 实测：
 * 纯色底 110ms 时白字低于 4.5:1 约 81ms、低于 3.0:1 约 65ms；380ms 时是 281 / 223ms。
 * 糊封面 + 同色蒙版那一段几乎只动彩度（实测 base L*31.9 → 合成场 L*36.5，白字 6.0 → 5.4），
 * 所以它可以慢 —— 淡入的"浮现感"由它承担，亮度那一下该快还是得快。
 */
export const COVER_BASE_FADE_MS = 110
export const COVER_WASH_FADE_MS = 340
